// ============================================================
// V7 チェック
// ============================================================
function checkV7(choices) {
  const lengths = choices.map(c => (c.text || '').length);
  const mx = Math.max(...lengths);
  const mn = Math.min(...lengths);
  if (mn === 0) return { ok: false, ratio: Infinity };
  return { ok: mx / mn <= 1.6, ratio: mx / mn };
}

// ============================================================
// 専門語密度計算（audit-questions.mjs と同一ロジック）
// ============================================================
function calcSpecialityDensity(text) {
  const katakana = (text.match(/[ァ-ヶー]{3,}/g) || []).join('').length;
  const ascii = (text.match(/[A-Za-z]{2,}/g) || []).join('').length;
  const numeric = (text.match(/[0-9]+/g) || []).join('').length;
  const brackets = (text.match(/（[^）]*）/g) || []).join('').length;
  const total = text.length;
  if (total === 0) return 0;
  return (katakana + ascii + numeric + brackets) / total;
}

function checkSkew(choices, correctIndex) {
  const correctText = (choices[correctIndex] || {}).text || '';
  const wrongTexts = choices.filter((_, i) => i !== correctIndex).map(c => c.text || '');
  if (wrongTexts.length === 0) return false;
  const cd = calcSpecialityDensity(correctText);
  const avg = wrongTexts.reduce((s, t) => s + calcSpecialityDensity(t), 0) / wrongTexts.length;
  return cd > avg * 1.5 && cd > 0.15;
}

