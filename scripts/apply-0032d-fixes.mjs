for (const [ch, fixes] of Object.entries(fixesByChapter)) {
  const chNum = parseInt(ch);
  const data = loadChapter(chNum);

  let modified = false;
  for (const fix of fixes) {
    const qIndex = data.findIndex(q => q.id === fix.id);
    if (qIndex === -1) {
      console.error(`ERROR: ${fix.id} not found in ch${chNum}.json`);
      process.exit(1);
    }

    const q = data[qIndex];
    const original = JSON.parse(JSON.stringify(q)); // deep copy

    // 方針 B ガード: 許可されていない qid で correctIndex の choices を変更しようとしていないか確認
    if (fix.changes.choices) {
      for (const idx of Object.keys(fix.changes.choices)) {
        const i = parseInt(idx);
        if (i === q.correctIndex && !POLICY_B_ALLOWED.has(fix.id)) {
          console.error(`ABORT: Policy B violation - ${fix.id} is not in POLICY_B_ALLOWED but tries to change correctIndex choice`);
          process.exit(1);
        }
      }
    }

    const diffEntry = {
      id: fix.id,
      beforeChoices: q.choices.map(c => c.text),
      afterChoices: [],
      beforeRationales: q.optionRationales ? [...q.optionRationales] : [],
      afterRationales: [],
    };

    // Apply choices changes
    if (fix.changes.choices) {
      for (const [idx, val] of Object.entries(fix.changes.choices)) {
        const i = parseInt(idx);
        q.choices[i] = { ...q.choices[i], ...val };
      }
    }

    // V7 check
    const v7 = checkV7(q.choices);
    if (!v7.ok) {
      console.warn(`WARN: V7 violation for ${fix.id} (ratio=${v7.ratio.toFixed(2)}). Reverting changes.`);
      // Revert
      data[qIndex] = original;
      skippedQids.push({ id: fix.id, reason: `V7 violation (ratio=${v7.ratio.toFixed(2)})` });
      abortCount++;
      continue;
    }

    // Apply optionRationales changes
    if (fix.changes.optionRationales) {
      if (!q.optionRationales) q.optionRationales = new Array(q.choices.length).fill('');
      for (const [idx, val] of Object.entries(fix.changes.optionRationales)) {
        q.optionRationales[parseInt(idx)] = val;
      }
    }

    // Apply misconceptionTarget
    if (fix.changes.misconceptionTarget) {
      q.misconceptionTarget = fix.changes.misconceptionTarget;
    }

    // Add qualityFlags
    if (!q.qualityFlags) q.qualityFlags = [];
    if (!q.qualityFlags.includes('fixed_in_0032d')) {
      q.qualityFlags.push('fixed_in_0032d');
    }

    // Check immutable fields
    const violations = checkImmutableFields(original, q, fix.id);
    if (violations.length > 0) {
      console.error('ABORT: Immutable field violation detected!');
      violations.forEach(v => console.error('  ' + v));
      // Revert all changes and exit
      process.exit(1);
    }

    // Check skew resolved
    const skewResolved = !checkSkew(q.choices, q.correctIndex);
    if (!skewResolved) {
      console.warn(`WARN: Skew not resolved for ${fix.id} after fix. Applied anyway (may need stronger correction).`);
    }

    diffEntry.afterChoices = q.choices.map(c => c.text);
    diffEntry.afterRationales = q.optionRationales ? [...q.optionRationales] : [];

    diffEntries.push(diffEntry);
    appliedQids.push(fix.id);
    modified = true;
  }

  if (modified && isWrite) {
    saveChapter(chNum, data);
    console.log(`Written: ch${chNum}.json (${fixes.filter(f => appliedQids.includes(f.id)).length} fixes applied)`);
  } else if (modified && isDryRun) {
    console.log(`DRY-RUN: would write ch${chNum}.json`);
  }
}

