// チャプターマッピング
function getChapter(id) {
  const match = id.match(/^(ch\d+)-/);
  return match ? match[1] : null;
}

// メイン処理
const chapters = ['ch1', 'ch2', 'ch3', 'ch4', 'ch5', 'ch6', 'ch7', 'ch8'];
const QUALITY_FLAG = 'rewritten_in_0032b_full';
const DEFINITION_PATTERN = /[^\s]{1,20}(とは|とはなにか|とは何か|の説明として正しい|の定義として正しい|について正しく説明している)/;

// リライトデータをidキーでマップ
const rewriteMap = new Map();
for (const r of REWRITE_DATA) {
  rewriteMap.set(r.id, r);
}

// 各章を処理
const stats = { success: 0, failed: 0, defTypeResolved: 0 };
const results = [];

for (const ch of chapters) {
  const p = join(projectRoot, 'src/data/questions', `${ch}.json`);
  const data = JSON.parse(readFileSync(p, 'utf-8'));
  let changed = false;

  const updated = data.map(q => {
    const rewrite = rewriteMap.get(q.id);
    if (!rewrite) return q;

    // 不変フィールド検証
    const immutableOk = IMMUTABLE_FIELDS.every(f => {
      const orig = JSON.stringify(q[f]);
      return orig !== undefined; // 元フィールドが存在すること
    });

    if (!immutableOk) {
      process.stderr.write(`[GUARD] 不変フィールド問題: ${q.id}\n`);
      return q;
    }

    // バリデーション
    if (DEFINITION_PATTERN.test(rewrite.question)) {
      process.stderr.write(`[FAIL] ${q.id}: question still matches definition pattern\n`);
      stats.failed++;
      return q;
    }
    if (!['understand', 'compare', 'apply'].includes(rewrite.cognitiveLevel)) {
      process.stderr.write(`[FAIL] ${q.id}: invalid cognitiveLevel: ${rewrite.cognitiveLevel}\n`);
      stats.failed++;
      return q;
    }
    if (rewrite.choices.length !== 4) {
      process.stderr.write(`[FAIL] ${q.id}: choices.length != 4\n`);
      stats.failed++;
      return q;
    }
    if (rewrite.correctIndex < 0 || rewrite.correctIndex > 3) {
      process.stderr.write(`[FAIL] ${q.id}: correctIndex out of range\n`);
      stats.failed++;
      return q;
    }
    if (rewrite.explanation.length < 40) {
      process.stderr.write(`[FAIL] ${q.id}: explanation too short: ${rewrite.explanation.length}\n`);
      stats.failed++;
      return q;
    }
    if (rewrite.optionRationales.length !== 4) {
      process.stderr.write(`[FAIL] ${q.id}: optionRationales.length != 4\n`);
      stats.failed++;
      return q;
    }

    // 文字数比チェック (V7: max/min <= 1.6)
    const choiceLengths = rewrite.choices.map(c => c.text.length);
    const minLen = Math.min(...choiceLengths);
    const maxLen = Math.max(...choiceLengths);
    if (minLen === 0 || maxLen / minLen > 1.6) {
      process.stderr.write(`[WARN] ${q.id}: choice length ratio: ${(maxLen/minLen).toFixed(2)} (limit 1.6)\n`);
    }

    // qualityFlags 更新
    const existingFlags = Array.isArray(q.qualityFlags) ? q.qualityFlags.filter(f => f !== QUALITY_FLAG) : [];
    const newFlags = [...existingFlags, QUALITY_FLAG];

    const updatedQ = {
      ...q,
      question: rewrite.question,
      choices: rewrite.choices,
      correctIndex: rewrite.correctIndex,
      explanation: rewrite.explanation,
      cognitiveLevel: rewrite.cognitiveLevel,
      learningObjective: rewrite.learningObjective,
      misconceptionTarget: rewrite.misconceptionTarget,
      optionRationales: rewrite.optionRationales,
      qualityFlags: newFlags,
    };

    // 不変フィールド最終確認
    for (const f of IMMUTABLE_FIELDS) {
      if (JSON.stringify(updatedQ[f]) !== JSON.stringify(q[f])) {
        process.stderr.write(`[GUARD2] 不変フィールドが変更されました: ${q.id} フィールド: ${f}\n`);
        process.exit(1);
      }
    }

    stats.success++;
    if (!DEFINITION_PATTERN.test(rewrite.question)) stats.defTypeResolved++;
    results.push({ id: q.id, ch, before: q, after: updatedQ });
    changed = true;
    process.stderr.write(`[OK] ${q.id} -> cognitiveLevel: ${q.cognitiveLevel} -> ${rewrite.cognitiveLevel}\n`);
    return updatedQ;
  });

  if (changed) {
    writeFileSync(p, JSON.stringify(updated, null, 2) + '\n', 'utf-8');
    process.stderr.write(`${ch}.json 更新完了\n`);

    // ガード3: 書き込み後の再確認
    const written = JSON.parse(readFileSync(p, 'utf-8'));
    for (const q of written) {
      const orig = data.find(x => x.id === q.id);
      if (!orig) continue;
      for (const f of IMMUTABLE_FIELDS) {
        if (JSON.stringify(q[f]) !== JSON.stringify(orig[f])) {
          process.stderr.write(`[GUARD3] 書き込み後に不変フィールドの差異検出: ${q.id} フィールド: ${f}\n`);
          process.exit(1);
        }
      }
    }
  }
}

process.stderr.write(`\n完了: 成功 ${stats.success} 件 / 失敗 ${stats.failed} 件 / 定義型解消 ${stats.defTypeResolved} 件\n`);

// 結果をstdoutに出力（diffレポート用）
process.stdout.write(JSON.stringify(results, null, 2));
